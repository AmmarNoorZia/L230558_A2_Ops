"""VisionGuard Task 2: real CNN and MobileNetV2 training, evaluation, visual artifacts.

Run from project root using 05_TRAIN_BASELINE.bat then 06_TRAIN_TRANSFER.bat.
Training/validation/test splits are generated by Step 1; duplicated SHA-256 images excluded.
"""
from __future__ import annotations
import argparse
import csv
import json
import os
import random
import shutil
import sys
from pathlib import Path

os.environ.setdefault('TF_CPP_MIN_LOG_LEVEL', '2')
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import tensorflow as tf
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score, precision_score,
                             recall_score, roc_auc_score, roc_curve, ConfusionMatrixDisplay)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'outputs'
MODELS = ROOT / 'models'
OUT.mkdir(exist_ok=True)
MODELS.mkdir(exist_ok=True)
IMG_SIZE = 128
BATCH = 16
SEED = 42
LABELS = {'Real': 0, 'AI-generated': 1}


def records(split):
    filename = OUT / f'{split}_split.csv'
    if not filename.exists():
        raise FileNotFoundError(f'Missing {filename}: finish 02_ANALYZE_DATA.bat first.')
    with filename.open(newline='', encoding='utf-8-sig') as fh:
        rows = list(csv.DictReader(fh))
    paths = [str(ROOT / row['path']) for row in rows]
    targets = np.array([LABELS[row['class_label']] for row in rows], dtype=np.int32)
    for p in paths:
        if not Path(p).exists():
            raise FileNotFoundError(f'Dataset image missing: {p}')
    return paths, targets


def load_image(path, target):
    image = tf.io.decode_image(tf.io.read_file(path), channels=3, expand_animations=False)
    image.set_shape((None, None, 3))
    # Preserves aspect ratio by adding letterbox padding, unlike naive stretching.
    image = tf.image.resize_with_pad(tf.cast(image, tf.float32), IMG_SIZE, IMG_SIZE)
    return image, tf.cast(target, tf.float32)


def pipeline(split, *, shuffle=False):
    paths, ys = records(split)
    ds = tf.data.Dataset.from_tensor_slices((paths, ys))
    if shuffle:
        ds = ds.shuffle(buffer_size=len(paths), seed=SEED, reshuffle_each_iteration=True)
    ds = ds.map(load_image, num_parallel_calls=tf.data.AUTOTUNE)
    return ds.batch(BATCH).prefetch(tf.data.AUTOTUNE)


def augmentation():
    return tf.keras.Sequential([
        tf.keras.layers.RandomFlip('horizontal', seed=SEED),
        tf.keras.layers.RandomRotation(0.055, fill_mode='reflect', seed=SEED),
        tf.keras.layers.RandomZoom(0.08, seed=SEED),
    ], name='train_only_augmentation')


def augmented_grid(train):
    images, _ = next(iter(train.take(1)))
    aug = augmentation()
    pictures = aug(images[:8], training=True).numpy().clip(0, 255).astype('uint8')
    fig, axes = plt.subplots(2, 4, figsize=(10, 5))
    for ax, img in zip(axes.flat, pictures):
        ax.imshow(img)
        ax.axis('off')
    fig.suptitle('Task 2.1: Augmentation applied to training samples only')
    fig.tight_layout()
    dest = OUT / 'augmented_training_batch.png'
    fig.savefig(dest, dpi=130)
    plt.close(fig)
    print('Saved', dest)


def baseline_model():
    inputs = tf.keras.Input(shape=(IMG_SIZE, IMG_SIZE, 3), name='rgb_image_0_to_255')
    x = augmentation()(inputs)
    x = tf.keras.layers.Rescaling(1.0 / 255.0)(x)
    for filters in (16, 32, 64):
        x = tf.keras.layers.Conv2D(filters, 3, padding='same', use_bias=False)(x)
        x = tf.keras.layers.BatchNormalization()(x)
        x = tf.keras.layers.Activation('relu')(x)
        x = tf.keras.layers.MaxPooling2D()(x)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    x = tf.keras.layers.Dropout(.35, seed=SEED)(x)
    outputs = tf.keras.layers.Dense(1, activation='sigmoid', name='ai_probability')(x)
    return tf.keras.Model(inputs, outputs, name='visionguard_baseline_cnn')


def transfer_model():
    inputs = tf.keras.Input(shape=(IMG_SIZE, IMG_SIZE, 3), name='rgb_image_0_to_255')
    x = augmentation()(inputs)
    # Exactly MobileNetV2's expected pixel scaling [-1, 1], embedded in saved model.
    x = tf.keras.layers.Rescaling(scale=1 / 127.5, offset=-1.0)(x)
    base = tf.keras.applications.MobileNetV2(
        input_shape=(IMG_SIZE, IMG_SIZE, 3), alpha=0.35, include_top=False,
        weights='imagenet')
    base.trainable = False
    x = base(x, training=False)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    x = tf.keras.layers.Dropout(.30, seed=SEED)(x)
    output = tf.keras.layers.Dense(1, activation='sigmoid', name='ai_probability')(x)
    return tf.keras.Model(inputs, output, name='visionguard_mobilenetv2'), base


def compile_model(model, lr):
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=lr),
                  loss=tf.keras.losses.BinaryCrossentropy(),
                  metrics=[tf.keras.metrics.BinaryAccuracy(name='accuracy'),
                           tf.keras.metrics.AUC(name='auc')])


def train_stage(model, train, val, *, epochs, lr, filepath, prefix):
    compile_model(model, lr)
    with (OUT / f'{prefix}_model_summary.txt').open('w', encoding='utf-8') as stream:
        model.summary(print_fn=lambda line, **kwargs: stream.write(line + '\n'))
    callbacks = [
        tf.keras.callbacks.ModelCheckpoint(str(filepath), monitor='val_loss', mode='min', save_best_only=True),
        tf.keras.callbacks.EarlyStopping(monitor='val_loss', patience=2, restore_best_weights=True),
        tf.keras.callbacks.ReduceLROnPlateau(monitor='val_loss', patience=1, factor=0.5, min_lr=1e-6),
    ]
    hist = model.fit(train, validation_data=val, epochs=epochs, callbacks=callbacks, verbose=2)
    with (OUT / f'{prefix}_history.json').open('w', encoding='utf-8') as fp:
        json.dump({k: [float(x) for x in v] for k, v in hist.history.items()}, fp, indent=2)
    history_plot(hist.history, prefix)
    best_epoch = int(np.argmin(hist.history['val_loss']) + 1)
    print(f'{prefix}: best epoch based on validation loss = {best_epoch}')
    return hist


def history_plot(h, prefix):
    fig, axs = plt.subplots(1, 2, figsize=(11, 4))
    for ax, key, heading in zip(axs, ('loss', 'accuracy'), ('Loss', 'Accuracy')):
        ax.plot(h[key], marker='o', label=f'train {key}')
        ax.plot(h[f'val_{key}'], marker='o', label=f'validation {key}')
        best = int(np.argmin(h['val_loss']))
        ax.axvline(best, color='gray', linestyle='--', label='best val-loss epoch')
        ax.set_title(f'{prefix}: {heading}')
        ax.set_xlabel('Epoch (zero-based)')
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / f'{prefix}_curves.png', dpi=160)
    plt.close(fig)


def probabilities(model, ds):
    return np.asarray(model.predict(ds, verbose=0), dtype=np.float64).reshape(-1)


def threshold_for_val(y, p):
    # Choose threshold on validation, NEVER using the held-out test outcomes.
    thresholds = np.linspace(.2, .8, 61)
    scores = [f1_score(y, p >= t, zero_division=0) for t in thresholds]
    return float(thresholds[int(np.argmax(scores))])


def assess(model, prefix):
    _, yval = records('val')
    _, ytest = records('test')
    pval = probabilities(model, pipeline('val'))
    threshold = threshold_for_val(yval, pval)
    ptest = probabilities(model, pipeline('test'))
    pred = (ptest >= threshold).astype(int)
    metrics = {'model': prefix, 'threshold_from_validation': threshold,
               'validation_f1': float(f1_score(yval, pval >= threshold, zero_division=0)),
               'accuracy': float(accuracy_score(ytest, pred)),
               'precision': float(precision_score(ytest, pred, zero_division=0)),
               'recall': float(recall_score(ytest, pred, zero_division=0)),
               'f1': float(f1_score(ytest, pred, zero_division=0)),
               'roc_auc': float(roc_auc_score(ytest, ptest))}
    (OUT / f'{prefix}_metrics.json').write_text(json.dumps(metrics, indent=2), encoding='utf-8')
    fig, ax = plt.subplots(figsize=(5, 4))
    ConfusionMatrixDisplay(confusion_matrix(ytest, pred), display_labels=['Real', 'AI-generated']).plot(ax=ax, cmap='Blues', colorbar=False)
    fig.tight_layout()
    fig.savefig(OUT / f'{prefix}_confusion_matrix.png', dpi=160)
    plt.close(fig)
    fpr, tpr, _ = roc_curve(ytest, ptest)
    fig, ax = plt.subplots(figsize=(5, 4))
    ax.plot(fpr, tpr, label=f'AUC {metrics["roc_auc"]:.3f}')
    ax.plot([0, 1], [0, 1], linestyle='--', color='gray')
    ax.set(xlabel='False positive rate', ylabel='True positive rate', title=prefix + ' ROC')
    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT / f'{prefix}_roc.png', dpi=160)
    plt.close(fig)
    error_grid(prefix, ytest, ptest, pred)
    print('\nFINAL TEST METRICS:', json.dumps(metrics, indent=2))
    return metrics


def error_grid(prefix, ytest, ptest, predicted):
    paths, _ = records('test')
    mistakes = np.flatnonzero(ytest != predicted)[:10]
    if len(mistakes) == 0:
        (OUT / f'{prefix}_misclassification_notes.txt').write_text('There were zero errors on the test set. No examples were invented.\n', encoding='utf-8')
        return
    from PIL import Image
    cols = 5
    rows = int(np.ceil(len(mistakes)/cols))
    fig, axs = plt.subplots(rows, cols, figsize=(15, 3.2 * rows), squeeze=False)
    for ax in axs.flat:
        ax.axis('off')
    for ax, idx in zip(axs.flat, mistakes):
        with Image.open(paths[idx]) as img:
            ax.imshow(img.convert('RGB'))
        ax.set_title(f'True: {"AI" if ytest[idx] else "Real"} | P(AI)={ptest[idx]:.2f}', fontsize=9)
    fig.suptitle(f'{prefix} — {len(mistakes)} misclassified test images (up to 10)')
    fig.tight_layout()
    fig.savefig(OUT / f'{prefix}_misclassified.png', dpi=140)
    plt.close(fig)


def candidate_checkpoints():
    paths = [MODELS / 'baseline.keras', MODELS / 'transfer_head.keras', MODELS / 'transfer_finetuned.keras']
    return [p for p in paths if p.exists()]


def select_champion():
    """Choose on validation F1 only; use held-out test only for reporting per experiment."""
    yval = records('val')[1]
    choices = []
    for filename in candidate_checkpoints():
        model = tf.keras.models.load_model(filename)
        prob = probabilities(model, pipeline('val'))
        t = threshold_for_val(yval, prob)
        score = float(f1_score(yval, prob >= t, zero_division=0))
        choices.append((score, filename, t))
        print(f'Candidate: {filename.name} | val F1={score:.4f} | threshold={t:.3f}')
    if not choices:
        raise RuntimeError('No saved models to choose from.')
    # In a tie prefer the first saved model rather than inspecting test results.
    best = max(choices, key=lambda x: x[0])
    shutil.copy2(best[1], MODELS / 'champion.keras')
    details = {'selected_file': best[1].name, 'version': best[1].stem,
               'validation_f1': best[0], 'threshold': best[2],
               'labels': {'0': 'Real', '1': 'AI-generated'},
               'image_size': IMG_SIZE, 'input_range': '0..255 RGB',
               'preprocess': 'tf.image.resize_with_pad to 128x128; saved model embeds normalization'}
    (MODELS / 'champion_metadata.json').write_text(json.dumps(details, indent=2), encoding='utf-8')
    print('CHAMPION:', best[1].name, 'saved as models/champion.keras')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--mode', choices=['baseline', 'transfer'], required=True)
    parser.add_argument('--baseline-epochs', type=int, default=6)
    parser.add_argument('--head-epochs', type=int, default=4)
    parser.add_argument('--fine-epochs', type=int, default=3)
    args = parser.parse_args()
    random.seed(SEED); np.random.seed(SEED); tf.keras.utils.set_random_seed(SEED)
    try:
        tf.config.experimental.enable_op_determinism()
    except Exception:
        pass
    print('VisionGuard Task 2 | TF', tf.__version__, '| mode', args.mode, '| images', IMG_SIZE, '| batch', BATCH, flush=True)
    for name in ('train', 'val', 'test'):
        _, labels = records(name)
        print(name, len(labels), '| AI', int(sum(labels)), '| Real', len(labels)-int(sum(labels)))
    train, val = pipeline('train', shuffle=True), pipeline('val')
    if not (OUT / 'augmented_training_batch.png').exists():
        augmented_grid(train)
    if args.mode == 'baseline':
        model = baseline_model()
        path = MODELS / 'baseline.keras'
        train_stage(model, train, val, epochs=args.baseline_epochs, lr=1e-3, filepath=path, prefix='baseline')
        best = tf.keras.models.load_model(path)
        assess(best, 'baseline')
    else:
        try:
            model, base = transfer_model()
        except Exception as exc:
            print('ERROR loading ImageNet MobileNetV2. First run downloads pretrained weights.', file=sys.stderr)
            print(str(exc), file=sys.stderr)
            raise
        first = MODELS / 'transfer_head.keras'
        train_stage(model, train, val, epochs=args.head_epochs, lr=1e-3, filepath=first, prefix='transfer_head')
        head_best = tf.keras.models.load_model(first)
        assess(head_best, 'transfer_head')
        # Fine tune last 20 layers, keeping all BatchNorm statistics fixed.
        base.trainable = True
        for layer in base.layers[:-20]:
            layer.trainable = False
        for layer in base.layers[-20:]:
            layer.trainable = not isinstance(layer, tf.keras.layers.BatchNormalization)
        print('Fine-tuning trainable backbone layers:', [layer.name for layer in base.layers if layer.trainable])
        second = MODELS / 'transfer_finetuned.keras'
        train_stage(model, train, val, epochs=args.fine_epochs, lr=1e-5, filepath=second, prefix='transfer_finetuned')
        fine_best = tf.keras.models.load_model(second)
        assess(fine_best, 'transfer_finetuned')
    select_champion()
    print('\nSUCCESS: Model training, checkpoints, plots and test reports saved.')
    print('Model for Flask inference: models/champion.keras')


if __name__ == '__main__':
    main()
